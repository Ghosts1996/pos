/** «Петров Иван Сергеевич» → «Петров И. С.» для подписи. */
function shortName(full) {
  const parts = String(full || "").replace(/^ИП\s+/i, "").replace(/^индивидуальный предприниматель\s+/i, "").trim().split(/\s+/);
  if (parts.length < 2) return parts[0] || LINE;
  return `${parts[0]} ${parts.slice(1).map((p) => `${p[0]}.`).join(" ")}`;
}

function ipName(full) {
  const f = String(full || "").trim();
  if (!f) return `индивидуальный предприниматель ${LINE}`;
  return /^ИП(?![А-Яа-яЁё])|индивидуальн/i.test(f) ? f : `индивидуальный предприниматель ${f}`;
}


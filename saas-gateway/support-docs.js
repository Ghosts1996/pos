const DOCS = Object.entries(TEMPLATES).map(([id, t]) => ({ id, title: t.title, hint: t.hint }));

/** Документ id с данными заведения → { filename, buffer, title, hint, filled }. */
function buildDoc(id, data = {}) {
  const t = TEMPLATES[id];
  if (!t) return null;
  const c = contextOf(data);
  const safeVenue = String((data.venue && data.venue.name) || "").replace(/[^\wА-Яа-яЁё-]+/g, "_").slice(0, 30);
  return {
    filename: `${t.file}${safeVenue ? `_${safeVenue}` : ""}.docx`,
    buffer: docx(t.build(c)),
    title: t.title,
    hint: t.hint,
    filled: c.filled,
  };
}

module.exports = { DOCS, buildDoc, docx, zip, crc32, contextOf };

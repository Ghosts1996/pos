const LINE = "________________";
const val = (v, blank = LINE) => (String(v || "").trim() ? String(v).trim() : blank);
// Не \b: в JS он не видит границу у кириллицы.
const isOrg = (name) => /^(ООО|АО|ПАО|ЗАО|ОАО|НКО|АНО)(?![А-Яа-яЁё])|общество|товарищество|кооператив/i.test(String(name || ""));
const WEEK = ["понедельник", "вторник", "среда", "четверг", "пятница", "суббота", "воскресенье"];

/** Сведения для шаблонов из профиля заведения и реквизитов платформы. */
function contextOf({ venue = {}, platform = {}, now = new Date() } = {}) {
  const legal = String(venue.sellerName || "").trim();
  const org = isOrg(legal);
  const d = new Date(now.getTime() + 3 * 3600 * 1000);
  const hours = venue.workingHours && typeof venue.workingHours === "object"
    ? Object.entries(venue.workingHours).sort((a, b) => Number(a[0]) - Number(b[0]))
      .map(([k, v]) => `${WEEK[(Number(k) || 1) - 1] || k}: ${v}`).join("; ")
    : "";
  const p = platform || {};
  const zalpos = p.fullName
    ? `${/^ИП(?![А-Яа-яЁё])|индивидуальн/i.test(p.fullName) ? p.fullName : `индивидуальный предприниматель ${p.fullName}`}, ИНН ${val(p.inn)}, ОГРНИП ${val(p.ogrnip)}, адрес: ${val(p.address)} — правообладатель платформы ZalPOS`
    : "индивидуальный предприниматель — правообладатель платформы ZalPOS (реквизиты указаны в публичной оферте на сайте https://zalpos.ru)";
  return {
    org,
    operator: legal ? `${legal}, ИНН ${val(venue.sellerInn)}, ${org ? "ОГРН" : "ОГРНИП"} ${val(venue.sellerOgrn)}, адрес: ${val(venue.sellerAddress)}` : `${LINE} (наименование организации или ФИО ИП), ИНН ${LINE}, ОГРН/ОГРНИП ${LINE}, адрес: ${LINE}`,
    legal: val(legal),
    inn: val(venue.sellerInn),
    ogrn: val(venue.sellerOgrn),
    legalAddress: val(venue.sellerAddress),
    venueName: val(venue.name),
    venueAddress: val(venue.address),
    venuePhone: val(venue.phone),
    hours: val(hours),
    rules: String(venue.rules || "").trim(),
    head: org ? "Генеральный директор" : "Индивидуальный предприниматель",
    zalpos,
    zalposEmail: val(p.email, "указан в публичной оферте на сайте https://zalpos.ru"),
    date: `«___» ____________ ${d.getUTCFullYear()} г.`,
    filled: !!legal,
  };
}


/// Согласия гостя перед первой отправкой имени, телефона или адреса:
/// на обработку персональных данных (ст. 9 152-ФЗ) и на трансграничную
/// передачу (ст. 12) — профиль, брони и заказы синхронизируются через
/// Google Firebase. С 1 сентября 2025 года согласие оформляется отдельно
/// от других документов, поэтому — две отдельные галочки со своими
/// текстами, а не строчка «принимаю политику».
///
/// Спрашиваем один раз на редакцию текста: отметка хранится на сервере в
/// РФ (доказательство), её номер — в профиле гостя (другие устройства) и
/// на этом устройстве (заказ без профиля).
class GuestConsent extends ChangeNotifier {
  /// Меняется вместе с текстами ниже — тогда гостя спросят заново.
  static const edition = '2026-10-09';
  static const editionLabel = 'Редакция от 9 октября 2026 г.';

  bool _pd = false;
  bool _crossBorder = false;

  /// В сборке одного заведения своя политика и свои документы.
  bool _given = !kSaasMode;

  bool get pd => _pd;
  bool get crossBorder => _crossBorder;
  bool get given => _given;

  /// Можно отправлять данные: согласия уже есть или обе галочки стоят.
  bool get ready => _given || (_pd && _crossBorder);

  set pd(bool v) {
    _pd = v;
    notifyListeners();
  }

  set crossBorder(bool v) {
    _crossBorder = v;
    notifyListeners();
  }

  static String _key(String uid) => 'guest_consent:${AppScope.tenantId ?? ''}:$uid';

  /// Согласие этой редакции уже было — в профиле или на этом устройстве.
  Future<void> load(String uid, [ClientProfile? profile]) async {
    if (_given) return;
    if (profile?.consentEdition == edition) {
      _markGiven();
      return;
    }
    try {
      final prefs = await SharedPreferences.getInstance();
      if (prefs.getString(_key(uid)) == edition) _markGiven();
    } catch (_) {}
  }

  /// Профиль пришёл позже (стрим) — подхватываем отметку из него.
  void sync(ClientProfile? profile) {
    if (!_given && profile?.consentEdition == edition) _markGiven();
  }

  void _markGiven() {
    _given = true;
    notifyListeners();
  }

  /// Записать согласие на сервер в РФ до отправки данных. Без обеих
  /// галочек не пускаем — кнопка и так неактивна, это страховка.
  Future<void> commit(String uid) async {
    if (_given) return;
    if (!_pd || !_crossBorder) {
      throw PiiGatewayException('Отметьте оба согласия — без них данные не отправить');
    }
    await PiiGatewayService().recordGuestConsent(edition);
    try {
      await (await SharedPreferences.getInstance()).setString(_key(uid), edition);
    } catch (_) {}
    _markGiven();
  }

  // ---------------------------------------------------------------- тексты

  /// Кто оператор: продавец из Профиля заведения, а пока его нет — само
  /// заведение по названию.
  static String operatorLine(VenueProfile v) {
    if (v.sellerReady) {
      final ogrn = v.sellerOgrn.length == 15 ? 'ОГРНИП' : 'ОГРН';
      return '${v.sellerName.trim()} (ИНН ${v.sellerInn}, $ogrn ${v.sellerOgrn}, '
          'адрес: ${v.sellerAddress.trim()})';
    }
    final name = v.name.trim();
    return '${name.isEmpty ? 'заведение' : 'заведение «$name»'}, чьим приложением я пользуюсь '
        '(полные реквизиты — у персонала заведения)';
  }

  static const pdTitle = 'Согласие на обработку персональных данных';
  static const crossBorderTitle = 'Согласие на трансграничную передачу персональных данных';

  static List<String> pdText(VenueProfile v) => [
        'Отмечая этот пункт, я свободно, своей волей и в своём интересе даю согласие '
            'оператору — ${operatorLine(v)} — на обработку моих персональных данных на условиях ниже.',
        'Какие данные: имя; номер телефона; дата рождения, если я её укажу; адрес доставки, '
            'если я оформлю доставку; сведения о бронированиях, заказах, посещениях, бонусах '
            'и отзывах; идентификатор устройства.',
        'Зачем: программа лояльности (бонусы, уровни, скидки); бронирование столов и лист '
            'ожидания; приём, оплата и доставка заказов; связь со мной по брони и заказу; '
            'уведомления в приложении.',
        'Что с ними делают: сбор, запись, систематизация, накопление, хранение, уточнение, '
            'извлечение, использование, передача (предоставление, доступ) работникам заведения '
            'и обработчику, блокирование, удаление и уничтожение — с использованием средств '
            'автоматизации.',
        'По поручению оператора данные обрабатывает сервис ZalPOS (индивидуальный '
            'предприниматель, реквизиты — в политике конфиденциальности). Имя, телефон и адрес '
            'сначала записываются на сервер в России.',
        'Согласие действует до его отзыва, но не дольше 3 лет с последнего посещения. Отозвать '
            'согласие и удалить данные можно кнопкой «Удалить мои данные» в профиле или обратившись '
            'в заведение; накопленные бонусы при этом аннулируются.',
      ];

  static List<String> crossBorderText(VenueProfile v) => [
        'Отмечая этот пункт, я даю согласие оператору — ${operatorLine(v)} — на трансграничную '
            'передачу моих персональных данных компании Google LLC (сервис Firebase): хранение '
            'и синхронизация — в центрах обработки данных в Бельгии и Нидерландах, вход в '
            'приложение и push-уведомления — на серверах в США.',
        'Передаются: имя, номер телефона, дата рождения, адрес доставки, сведения о '
            'бронированиях, заказах, посещениях и бонусах, идентификатор устройства. Первично '
            'данные записываются на сервер в России.',
        'Зачем: чтобы приложение работало вместе с кассой заведения — персонал видел бронь и '
            'заказ, начислял бонусы, а приложение присылало уведомления. Получатель защищает '
            'данные: шифрование при хранении и передаче, сертификаты ISO/IEC 27001, 27017, 27018.',
        'Срок и порядок отзыва — как в согласии на обработку персональных данных. Без этого '
            'согласия приложение не может сохранить профиль, бронь или заказ.',
      ];
}

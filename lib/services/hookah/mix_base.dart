class MixPart {
  final String flavor;
  final int share;
  const MixPart(this.flavor, this.share);
}

class Mix {
  final String name;
  final List<MixPart> parts;
  final Set<String> tags;
  final String note;
  const Mix(this.name, this.parts, this.tags, this.note);

  Set<String> get flavors => {for (final p in parts) p.flavor};
}

Mix parseMixLine(String line) {
  final f = line.split('|');
  final parts = [
    for (final p in f[1].split(','))
      if (p.trim().isNotEmpty) MixPart(p.trim().split(' ').first, int.parse(p.trim().split(' ').last)),
  ];
  final tags = {for (final t in f[2].split(',')) t.trim()}..removeWhere((t) => t.isEmpty);
  return Mix(f[0], parts, tags, f.length > 3 ? f[3] : '');
}

final List<Mix> kMixes = [for (final l in kMixLines) parseMixLine(l)];
